// Minimal service worker — exists only to receive Web Push events and show
// the weekly progress-reminder notification (see src/lib/pushNotifications.ts
// for the subscribe flow and the send-progress-reminders edge function for
// the sender). No offline caching / asset precaching is done here.

self.addEventListener("install", () => {
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(self.clients.claim());
});

self.addEventListener("push", (event) => {
  let data = {};
  try {
    data = event.data ? event.data.json() : {};
  } catch {
    data = { body: event.data ? event.data.text() : "" };
  }

  const title = data.title || "Fitsush";
  const options = {
    body: data.body || "Time to log this week's progress!",
    icon: "/favicon.ico",
    badge: "/favicon.ico",
    data: { url: data.url || "/progress" },
  };

  event.waitUntil(self.registration.showNotification(title, options));
});

self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const targetUrl = event.notification.data?.url || "/progress";

  event.waitUntil(
    self.clients.matchAll({ type: "window", includeUncontrolled: true }).then((clientList) => {
      for (const client of clientList) {
        if (client.url.includes(targetUrl) && "focus" in client) return client.focus();
      }
      if (self.clients.openWindow) return self.clients.openWindow(targetUrl);
    }),
  );
});
